"""Export an int8 .tflite model as C sources for the firmware (Phase 2).

Usage (from ml/):
    uv run python scripts/export_model.py                         # default model + classes
    uv run python scripts/export_model.py --model models/X.tflite --classes 0,1,2,4

Writes firmware/app/src/model/:
- model_data.c / model_data.h: the flatbuffer as a 16-byte aligned byte array
- model_config.h: class IDs, input/output quantization, the per-channel input scale used
  in training (cnn.INPUT_SCALE), the IMU full scale, and the exact list of TFLM operators
  the model needs (so the firmware registers only those)

Everything the firmware needs to preprocess a window the same way as training comes from
here, so the two cannot drift apart silently.
"""

from __future__ import annotations

import argparse
import hashlib
import os
import re
from pathlib import Path

os.environ.setdefault("TF_CPP_MIN_LOG_LEVEL", "2")
import tensorflow as tf  # noqa: E402

from coleira_ml.classes import Behavior  # noqa: E402
from coleira_ml.cnn import INPUT_SCALE  # noqa: E402
from coleira_ml.public_dataset import ACCEL_RANGE_G, GYRO_RANGE_DPS  # noqa: E402

ROOT = Path(__file__).resolve().parents[2]
DEFAULT_MODEL = ROOT / "ml" / "models" / "cnn_multi_int8.tflite"
DEFAULT_OUT = ROOT / "firmware" / "app" / "src" / "model"

# TFLite builtin op name → MicroMutableOpResolver method
_SPECIAL = {"CONV_2D": "AddConv2D", "MAX_POOL_2D": "AddMaxPool2D", "DEPTHWISE_CONV_2D":
            "AddDepthwiseConv2D", "AVERAGE_POOL_2D": "AddAveragePool2D"}  # fmt: skip


def resolver_method(op: str) -> str:
    return _SPECIAL.get(op) or "Add" + "".join(p.capitalize() for p in op.split("_"))


def model_ops(path: Path) -> list[str]:
    it = tf.lite.Interpreter(
        model_path=str(path),
        experimental_op_resolver_type=tf.lite.experimental.OpResolverType.BUILTIN_WITHOUT_DEFAULT_DELEGATES,
    )
    return sorted({d["op_name"] for d in it._get_ops_details()})


def io_details(path: Path):
    it = tf.lite.Interpreter(model_path=str(path))
    return it.get_input_details()[0], it.get_output_details()[0]


def c_array(data: bytes, per_line: int = 16) -> str:
    lines = []
    for i in range(0, len(data), per_line):
        lines.append("\t" + ", ".join(f"0x{b:02x}" for b in data[i : i + per_line]) + ",")
    return "\n".join(lines)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--model", type=Path, default=DEFAULT_MODEL)
    ap.add_argument("--classes", default="0,1,2,4", help="class ID of each model output")
    ap.add_argument("--out", type=Path, default=DEFAULT_OUT)
    args = ap.parse_args()

    data = args.model.read_bytes()
    sha = hashlib.sha256(data).hexdigest()
    classes = [int(c) for c in args.classes.split(",")]
    inp, out = io_details(args.model)
    ops = model_ops(args.model)
    if inp["dtype"].__name__ != "int8" or out["dtype"].__name__ != "int8":
        raise SystemExit("model must have int8 input and output (full integer quantization)")
    _, window, channels = inp["shape"]
    if out["shape"][-1] != len(classes):
        raise SystemExit(f"model has {out['shape'][-1]} outputs but {len(classes)} classes given")
    if channels != len(INPUT_SCALE):
        raise SystemExit(f"model expects {channels} channels, INPUT_SCALE has {len(INPUT_SCALE)}")

    args.out.mkdir(parents=True, exist_ok=True)
    try:
        src = args.model.resolve().relative_to(ROOT).as_posix()
    except ValueError:
        src = args.model.name
    banner = (
        f"/* GENERATED by ml/scripts/export_model.py. Do not edit.\n"
        f" * source: {src}\n * sha256: {sha}\n */\n"
    )

    (args.out / "model_data.h").write_text(
        banner
        + "#ifndef MODEL_DATA_H_\n#define MODEL_DATA_H_\n\n"
        + '#ifdef __cplusplus\nextern "C" {\n#endif\n\n'
        + "extern const unsigned char g_model_data[];\n"
        + "extern const unsigned int g_model_data_len;\n\n"
        + "#ifdef __cplusplus\n}\n#endif\n\n#endif /* MODEL_DATA_H_ */\n",
        encoding="utf-8",
    )
    (args.out / "model_data.c").write_text(
        banner
        + '#include "model_data.h"\n\n'
        + "__attribute__((aligned(16))) const unsigned char g_model_data[] = {\n"
        + c_array(data)
        + f"\n}};\n\nconst unsigned int g_model_data_len = {len(data)};\n",
        encoding="utf-8",
    )

    in_scale, in_zp = inp["quantization"]
    out_scale, out_zp = out["quantization"]
    names = ", ".join(f'"{Behavior(c).name.lower()}"' for c in classes)
    scales = ", ".join(f"{float(s):.1f}f" for s in INPUT_SCALE)
    adds = " \\\n".join(f"\t\t(r).{resolver_method(o)}();" for o in ops)
    ids = ", ".join(map(str, classes))
    config = f"""{banner}#ifndef MODEL_CONFIG_H_
#define MODEL_CONFIG_H_

#define MODEL_WINDOW        {window}   /* samples per window (contract 4.3) */
#define MODEL_CHANNELS      {channels}     /* ax, ay, az, gx, gy, gz, |a| */
#define MODEL_N_CLASSES     {len(classes)}
#define MODEL_CLASS_IDS     {{{ids}}}  /* contract 4.1 IDs, one per output */
#define MODEL_CLASS_NAMES   {{{names}}}

/* Input quantization: q = round(x / MODEL_IN_SCALE) + MODEL_IN_ZERO_POINT */
#define MODEL_IN_SCALE      {in_scale:.9g}f
#define MODEL_IN_ZERO_POINT ({in_zp})
/* Output dequantization: p = (q - MODEL_OUT_ZERO_POINT) * MODEL_OUT_SCALE */
#define MODEL_OUT_SCALE     {out_scale:.9g}f
#define MODEL_OUT_ZERO_POINT ({out_zp})

/* Preprocessing used in training: x = physical_value / MODEL_CH_SCALE[c]
 * (accel in g, gyro in dps, |a| in g; coleira_ml.cnn.INPUT_SCALE) */
#define MODEL_CH_SCALE      {{{scales}}}
/* Full scale of the raw int16 samples (contract 4.2 / ADR 0005) */
#define MODEL_ACCEL_FS_G    {ACCEL_RANGE_G:.1f}f
#define MODEL_GYRO_FS_DPS   {GYRO_RANGE_DPS:.1f}f

/* TFLM operators used by this model */
#define MODEL_OP_COUNT      {len(ops)}
#define MODEL_REGISTER_OPS(r) \\
\tdo {{ \\
{adds} \\
\t}} while (0)

#endif /* MODEL_CONFIG_H_ */
"""
    (args.out / "model_config.h").write_text(re.sub(r"[ \t]+\n", "\n", config), encoding="utf-8")
    print(f"exported {args.model.name} ({len(data)} bytes, sha256 {sha[:12]}…) → {args.out}")
    print(f"  classes {classes}, ops {ops}")
    print(f"  input scale {in_scale:.6g} zp {in_zp}; output scale {out_scale:.6g} zp {out_zp}")


if __name__ == "__main__":
    main()
