"""How much labeled data do we have, and is Phase 1 done?

    uv run python scripts/own_data_report.py

Reads ml/data/raw/<session>/ + ml/data/labels/<session>.csv (sessions aligned in the
labeler) and writes docs/results/own_data.md: sessions, dogs, minutes per class, packet
loss, and the Phase 1 done criterion (≥ 2 h labeled, ≥ 5 dogs, ≥ 3 min of classes 0–4,
loss < 1%). No TensorFlow needed.
"""

from __future__ import annotations

import argparse
from pathlib import Path

from coleira_ml.classes import Behavior
from coleira_ml.own_sessions import load_sessions, minutes_per_class, phase1_check

ROOT = Path(__file__).resolve().parents[2]

OUT = ROOT / "docs" / "results" / "own_data.md"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument(
        "--data", type=Path, default=ROOT / "ml" / "data", help="folder with raw/ and labels/"
    )
    args = ap.parse_args()
    df, stats, skipped = load_sessions(args.data / "raw", args.data / "labels")
    sess = "\n".join(
        f"| {s.session_id} | {s.dog_id} | {s.day} | {s.minutes:.1f} | {s.labeled_minutes:.1f} | "
        f"{s.packet_loss:.2%} | {s.odr_hz:.2f} |"
        for s in stats
    )
    per_class = minutes_per_class(df)
    dogs = sorted({s.dog_id for s in stats})
    per_dog = df[df.class_id != 255].groupby(["dog_id", "class_id"]).size().unstack(fill_value=0)
    cls_cols = [c for c in range(7) if c in per_dog.columns]
    dog_rows = "\n".join(
        f"| {d} | " + " | ".join(f"{per_dog.loc[d, c] / 3000:.1f}" for c in cls_cols) + " |"
        for d in per_dog.index
    )
    check = "\n".join(
        f"| {name} | {'✅' if ok else '❌'} | {val} |" for name, ok, val in phase1_check(df, stats)
    )
    md = f"""# Our own labeled data

> Generated by `ml/scripts/own_data_report.py`. Do not edit by hand.

{len(stats)} sessions, {len(dogs)} dogs, {sum(s.labeled_minutes for s in stats) / 60:.2f} h labeled.

## Phase 1 done criterion

| Criterion | | Now |
|---|---|---|
{check}

## Minutes per class and dog

| Dog | {" | ".join(Behavior(c).name.lower() for c in cls_cols)} |
|---|{"---:|" * len(cls_cols)}
{dog_rows}
| **all** | {" | ".join(f"**{per_class.get(c, 0):.1f}**" for c in cls_cols)} |

## Sessions

| Session | Dog | Day | Minutes | Labeled | Packet loss | IMU rate (Hz) |
|---|---|---|---:|---:|---:|---:|
{sess}
"""
    if skipped:
        md += "\nSkipped: " + "; ".join(skipped) + "\n"
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(md, encoding="utf-8")
    print(md)


if __name__ == "__main__":
    main()
