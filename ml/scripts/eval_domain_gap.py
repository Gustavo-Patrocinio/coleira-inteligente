"""Domain gap: how does a model trained on public data do on OUR dogs and collar?

    uv run python scripts/eval_domain_gap.py
    uv run python scripts/eval_domain_gap.py --model models/cnn_multi_int8.tflite --classes 0,1,2,4

Runs the int8 model exactly as the chip would (quantized input) on every labeled window of
our own sessions (ml/data/raw + ml/data/labels, aligned in the labeler), keeping only the
classes the model knows. Nothing here was used to train it, so this is the honest "someone
else's dog, someone else's collar" number. Writes docs/results/domain_gap.md + a figure.
Phase 1 wrap-up task in CLAUDE.md.
"""

from __future__ import annotations

import argparse
from pathlib import Path

import numpy as np

from coleira_ml import cnn
from coleira_ml.own_sessions import load_sessions, own_windows
from coleira_ml.report import confusion_md, f1_text, name, save_confusion, scores

ROOT = Path(__file__).resolve().parents[2]

OUT = ROOT / "docs" / "results" / "domain_gap.md"
FIG = OUT.parent / "figures" / "domain_gap_confusion.png"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument(
        "--data", type=Path, default=ROOT / "ml" / "data", help="folder with raw/ and labels/"
    )
    ap.add_argument("--model", type=Path, default=ROOT / "ml" / "models" / "cnn_multi_int8.tflite")
    ap.add_argument("--classes", default="0,1,2,4", help="contract IDs of the model outputs")
    args = ap.parse_args()
    classes = [int(c) for c in args.classes.split(",")]
    tfl = args.model.read_bytes()

    df, stats, skipped = load_sessions(args.data / "raw", args.data / "labels")
    w = own_windows(df)
    unseen = {name(c): int((w.y == c).sum()) for c in set(w.y.tolist()) - set(classes) - {255}}
    w = w.subset(np.isin(w.y, classes))
    pred = np.asarray(classes)[cnn.predict_int8(tfl, w.X)]

    bacc, f1 = scores(w.y, pred, classes)
    rows = [f"| **all** ({len(set(w.dog))} dogs) | {len(w.y)} | {bacc:.3f} | {f1_text(f1)} |"]
    for dog in sorted(set(w.dog)):
        m = w.dog == dog
        b, f = scores(w.y[m], pred[m], classes)
        rows.append(f"| {dog} | {m.sum()} | {b:.3f} | {f1_text(f)} |")
    save_confusion(w.y, pred, classes, FIG, f"{args.model.name} on our dogs (bal. acc {bacc:.3f})")

    md = f"""# Domain gap: public-data model on our own dogs

> Generated by `ml/scripts/eval_domain_gap.py`. Do not edit by hand.

Model `{args.model.name}` ({len(tfl) / 1024:.1f} KB int8; outputs
{", ".join(name(c) for c in classes)}), run as on the chip (int8 input). Test data: our
{len(stats)} labeled sessions, {len(set(w.dog))} dogs, {len(w.y)} windows of those classes.
None of it was seen in training. Compare with the public-data numbers in
`multi_dataset.md` (unseen dogs of the same dataset, and cross-dataset).

| Dogs | Windows | Balanced acc. | F1 |
|---|---:|---:|---|
{chr(10).join(rows)}

{confusion_md(w.y, pred, classes)}

![Confusion matrix](figures/domain_gap_confusion.png)

Windows of classes the model does not have (left out above): {unseen or "none"}.
Inference RAM: read the arena use from the board log (`firmware/app`).
"""
    if skipped:
        md += "\nSkipped sessions: " + "; ".join(skipped) + "\n"
    OUT.write_text(md, encoding="utf-8")
    print(md)


if __name__ == "__main__":
    main()
