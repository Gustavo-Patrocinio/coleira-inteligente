"""Calibrate the event smoothing (ADR 0002): `p_event` and `n_min` per event class.

    uv run python scripts/calibrate_events.py      # LODO out-of-fold probs (finetune_lodo.py)
    uv run python scripts/calibrate_events.py --model models/X.tflite --classes 0,1,2,3,4 \
        --sessions s07,s12                         # or named validation sessions

Replays the firmware's smoothing (a Python port checked against smoothing.c) over every
stretch of consecutive windows, for each candidate, and scores events: recall, precision and
false events per hour. Best = highest mean event F1, then fewest false alarms.

Calibrate on data the model did not train on: by default the out-of-fold probabilities of
the leave-one-dog-out run (each window predicted by a model that never saw that dog), or
named validation sessions with --sessions. Writes docs/results/event_calibration.md and
prints the lines to change in firmware/app/src/main.c.
"""

from __future__ import annotations

import argparse
from pathlib import Path

import numpy as np

from coleira_ml.events import calibrate
from coleira_ml.report import name

ROOT = Path(__file__).resolve().parents[2]
ML = ROOT / "ml"
OOF = ML / "models" / "finetune_oof.npz"
OUT = ROOT / "docs" / "results" / "event_calibration.md"
EVENTS = [3, 4]


def from_oof(path: Path):
    d = np.load(path, allow_pickle=False)
    return (
        d["probs"],
        d["y"],
        d["stretch"],
        [int(c) for c in d["class_ids"]],
        f"`{path.name}` (LODO out-of-fold)",
    )


def from_model(model: Path, classes: list[int], sessions: list[str], data: Path):
    from coleira_ml import cnn
    from coleira_ml.own_sessions import load_sessions, own_windows

    df, _, _ = load_sessions(data / "raw", data / "labels", only=sessions)
    w = own_windows(df)
    probs = cnn.predict_int8_probs(model.read_bytes(), w.X)
    return probs, w.y, w.stretch, classes, f"`{model.name}` (int8) on {', '.join(sessions)}"


def sequences(probs, y, stretch):
    """Windows grouped by stretch, in time order (own_windows keeps that order)."""
    out = []
    for s in dict.fromkeys(stretch.tolist()):
        m = stretch == s
        out.append((probs[m], y[m]))
    return out


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--model", type=Path)
    ap.add_argument("--classes", default="0,1,2,3,4")
    ap.add_argument("--sessions", help="comma-separated validation session ids")
    ap.add_argument("--data", type=Path, default=ML / "data", help="folder with raw/ and labels/")
    ap.add_argument("--oof", type=Path, default=OOF)
    args = ap.parse_args()
    if args.model:
        if not args.sessions:
            raise SystemExit("--model needs --sessions (sessions the model did not train on)")
        probs, y, stretch, class_ids, source = from_model(
            args.model,
            [int(c) for c in args.classes.split(",")],
            args.sessions.split(","),
            args.data,
        )
    else:
        if not args.oof.exists():
            raise SystemExit(
                f"{args.oof} not found: run scripts/finetune_lodo.py first, or pass --model"
            )
        probs, y, stretch, class_ids, source = from_oof(args.oof)

    seqs = sequences(probs, y, stretch)
    ranked = calibrate(seqs, class_ids, EVENTS)
    ev = [c for c in EVENTS if c in class_ids]
    best = ranked[0]
    hours = sum(len(t) for _, t in seqs) / 3600

    def row(c):
        cells = []
        for e in ev:
            s = c.scores[e]
            cells.append(
                f"{s.recall:.2f} / {s.precision:.2f} / {s.false_per_hour:.1f}"
                if s.true_events
                else f"– / – / {s.false_per_hour:.1f}"
            )
        nmin = ", ".join(f"{name(e)} {c.n_min[e]}" for e in ev)
        return f"| {c.p_event:.1f} | {nmin} | {c.mean_f1:.2f} | " + " | ".join(cells) + " |"

    best_nmin = ", ".join(f"{name(e)} {best.n_min[e]}" for e in ev)
    true_counts = ", ".join(f"{name(e)} {best.scores[e].true_events}" for e in ev)
    md = f"""# Event smoothing calibration (ADR 0002)

> Generated by `ml/scripts/calibrate_events.py`. Do not edit by hand.

Source: {source}; {len(seqs)} stretches, {hours:.2f} h, true events: {true_counts}.
Smoothing replayed exactly as in the firmware (majority of 5 for states; an event needs
≥ `n_min` consecutive windows with probability ≥ `p_event`).

**Best: `p_event` = {best.p_event:.1f}, `n_min` = {best_nmin}**

Each event column: recall / precision / false events per hour.

| p_event | n_min | mean F1 | {" | ".join(name(e) for e in ev)} |
|---:|---|---:|{"---|" * len(ev)}
{chr(10).join(row(c) for c in ranked[:10])}

Firmware (`firmware/app/src/main.c`, `smooth_cfg`):

    .p_event = {best.p_event:.1f}f,
    sc.event_n_min[i] = {" : ".join(f"class_ids[i] == {e} ? {best.n_min[e]}" for e in ev)} : 0;
"""
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(md, encoding="utf-8")
    print(md)


if __name__ == "__main__":
    main()
